"""인덱스 재개 규율 — 무엇을 이미 했고, 이번에 무엇을 조회할 것인가.

**이 두 함수가 `ss_index_build.py` 본문에서 떨어져 나온 이유는 하나다: 검증 가능성.**

3시간 32분짜리 루프의 재개 규율은 **루프를 돌려서 검증할 수 없다.** 그 루프는 불사자
MCP 를 타고, `ss_index_build.py` 는 모듈 최상단에서 `bulsaja_mcp` 를 import 하므로
`.venv-web` 의 pytest 는 그 파일을 **import 조차 못 한다**(그 venv 에 `requests` 가 없다,
D-19). 그러면 Pitfall 6("페이지 번호로 재개하면 안 훑은 상품이 훑은 것으로 넘어간다")를
막는 계산이 스위트에 한 줄도 안 남고, 다음 사람이 그 한 줄을 고쳐도 아무도 모른다.

그래서 **import 가 0줄인 모듈**로 뽑았다. `bulsaja_rate.py` 와 같은 선이다 —
여기에 `bulsaja_mcp` 나 `requests` 를 한 줄이라도 끌어오는 순간 재개 회귀 테스트가
통째로 죽는다. `test_재개모듈은_아무것도_import하지_않는다` 가 그 선을 기계로 지킨다.

재개 단위는 **페이지 번호가 아니라 productId 집합**이다 (RESEARCH §Pitfall 6).
목록 조회의 정렬 기준이 문서화돼 있지 않고 실측 단조성이 61.9%라, 호출 사이에 물갈이
삭제·신규 수집이 끼면 페이지 경계가 밀린다.

⚠️ **미조회(`unresolved = 1`) 행은 "처리완료" 가 아니다.** 다음 실행이 다시 시도한다
(03-04 이탈 #1). 성공행만 건너뛴다 — 안 그러면 429 로 빠진 상품이 영원히 미조회로 굳고,
그 행이 화면에서 "미해소(= 광고 쪽 오류)" 로 보여 용팀장이 멀쩡한 광고그룹을 지우러 간다.
되돌릴 수 없다 (RESEARCH §Pitfall 3).
"""


def 처리완료(cx, 그룹아이디):
    """이 그룹에서 **성공적으로 적힌** product_id 집합 — 재개가 건너뛸 것들.

    `unresolved = 0` 만 센다. 미조회 행은 일부러 뺀다 (모듈 docstring 의 ⚠️).
    호출부가 커넥션을 준다 — 이 모듈은 DB 를 열지도, 만들지도, 쓰지도 않는다.
    """
    # 여기서 예외를 삼키지 않는다. 읽기가 실패하는 경우는 사실상 "테이블이 없다" 뿐이고,
    # 그건 `ss_index_build.스키마확인()` 이 **MCP 를 붙기도 전에** exit 4 로 거른다.
    # 여기서 빈 집합으로 접으면 "아무것도 안 했다" 가 되어 3시간을 통째로 다시 돈다.
    return {행[0] for 행 in cx.execute(
        "SELECT product_id FROM ss_index "
        "WHERE market_group_id = ? AND unresolved = 0", (그룹아이디,))}


def 남은대상(전체목록, 처리완료집합):
    """이번에 조회할 productId 목록. 순서는 `전체목록` 을 따른다.

    성질 셋을 여기서 보장한다:
      ① 처리완료에 있는 것은 뺀다 (재개의 본질)
      ② 순서에 의존하지 않는다 — `전체목록` 을 어떻게 뒤섞어도 결과 **집합**이 같다
      ③ 한 실행에서 같은 상품을 두 번 조회하지 않는다 (중복 입력이 와도 1회)
        ③은 `그룹상품목록` 이 이미 중복을 지우고 주므로 현재는 no-op 이지만,
        그 상위 보장이 깨져도 레이트리밋 예산이 조용히 새지 않게 여기서 한 번 더 못박는다.
    """
    남은, 본것 = [], set()
    for pid in 전체목록:
        if not pid or pid in 처리완료집합 or pid in 본것:
            continue
        본것.add(pid)
        남은.append(pid)
    return 남은
