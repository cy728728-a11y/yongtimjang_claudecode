class _상세이미지수집(HTMLParser):
    """`renderContent` 의 `<img src>` 를 **문서 순서대로** 모은다.

    정규식이 아니라 stdlib 파서를 쓰는 이유: 실측 태그는 `<div>`·`<img>` 둘뿐이지만
    (2026-09-21, 950 div / 916 img), 불사자가 마크업을 바꾸면 정규식은 **조용히 덜 집는다.**
    파서는 모양이 바뀌어도 `src` 를 계속 집거나 아예 아무것도 못 집는다 —
    "조용히 덜 집는" 것이 이 저장소가 CR-01~03 에서 가장 비싸게 배운 실패 모양이다.
    """

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.urls: list[str] = []

    def handle_starttag(self, tag, attrs):
        if tag.lower() != "img":
            return
        src = dict(attrs).get("src")
        # `src` 없는 `<img>` 는 실측 0건이다. 그래도 조용히 건너뛰지 말고 자리를 남겨라 —
        # 순번이 밀리면 사람 라벨(이미지순번 기준)이 **통째로** 어긋난다.
        self.urls.append(src if src else "")


def 상세이미지목록(render_content) -> list[str]:
    """`renderContent` 문자열 → URL 리스트. **모양이 아니면 예외.** (BANNER-01)

    `ss_index_calls.목록꺼내기` 의 규약을 그대로 쓴다 — "못 읽었다"와 "0개라 답했다"는
    다른 사실이다. `None` 은 "상세를 못 물어봤다"(실측 194행 중 137행)이고,
    빈 문자열은 "상세가 비었다"(실측 18건)다. 호출자가 둘을 구분할 수 있게 예외로 가른다.

    중복 URL 은 **두 번 다 남는다.** 중복 제거는 Phase 5 몫이고, 여기서 지우면 순번이
    밀려 사람 라벨이 어긋난다(실측 57건 중 3건이 중복을 갖는다).
    """
    if render_content is None:
        raise ValueError("renderContent 가 None 이다 — 미조회와 0장을 같은 값으로 접지 마라 "
                         "(실측 194행 중 137행이 이 모양이다)")
    if not isinstance(render_content, str):
        raise ValueError(f"renderContent 의 모양이 다르다: {type(render_content).__name__} "
                         "— 판이 바뀐 것이지 빈 결과가 아니다")
    수집 = _상세이미지수집()
    try:
        수집.feed(render_content)
        수집.close()
    except Exception as e:      # 파서가 터지는 것도 "0장"이 아니다. 사실대로 올린다.
        raise ValueError(f"renderContent 를 파싱하지 못했다: {e}") from e
    return 수집.urls


def 상세보유행들(조인문서: dict) -> list[dict]:
    """조인 산출물의 `행` 중 상세를 **실제로 들고 있는** 행만 (실측 194행 중 57행).

    `renderContent` 가 공백뿐이어도 **보유는 보유다** — 그건 "상세가 비었다"는 관측이고,
    `uploadDetailContents` 가 `None` 인 것("못 물어봤다")과 다른 사실이다.
    비었으면 `[]` 를 돌려준다. **0건은 0건이지 오류가 아니다.**
    """
    if not isinstance(조인문서, dict):
        raise ValueError(f"조인 산출물이 dict 가 아니다: {type(조인문서).__name__}")
    if "행" not in 조인문서:
        raise ValueError("조인 산출물에 '행' 키가 없다 — 못 물어본 것을 0건으로 읽지 마라")
    행들 = 조인문서.get("행")
    if not isinstance(행들, list):
        raise ValueError(f"조인 산출물의 '행' 이 리스트가 아니다: {type(행들).__name__}")

    보유 = []
    for i, 행 in enumerate(행들):
        if not isinstance(행, dict):
            raise ValueError(f"조인 산출물 {i}번째 행이 dict 가 아니다: {type(행).__name__}")
        if isinstance(행.get("uploadDetailContents"), dict):
            보유.append(행)
    return 보유


def 상품키(상품: dict) -> str:
    """타오바오상품번호. 없으면 불사자코드로 폴백 (성공기준 4 · `dedup.code_of` 규약).

    사본(팬아웃)이 실측 230건이다. 판매자상품코드로 묶으면 같은 타오바오 상품의 물갈이
    사본이 분모를 8배까지 부풀린다. URL 로 묶는 것도 안 된다 — 불사자는 수집할 때마다
    이미지를 상품별 CDN 경로에 새로 복사한다(D-01a 실측).

    **둘 다 없으면 예외다.** 빈 키로 묶으면 전 상품이 한 덩어리가 된다 —
    "빈 값이 전량이 되는 경로"의 집계판이다.
    """
    if not isinstance(상품, dict):
        raise ValueError(f"상품이 dict 가 아니다: {type(상품).__name__}")
    for 필드 in ("타오바오상품번호", "불사자코드"):
        값 = 상품.get(필드)
        if 값 is not None and str(값).strip():
            return str(값).strip()
    raise ValueError("타오바오상품번호도 불사자코드도 없다 — 빈 키로 묶으면 "
                     "전 상품이 한 덩어리가 된다 (성공기준 4)")


def 스킵사유읽기(상품: dict) -> str | None:
    """산출물의 `스킵사유` 를 **읽기만** 한다. 규칙을 재현하지 않는다 (S-1).

    D-07(잔여 하한)·D-08(제거율 상한) 판정의 정본은 `banner_scan.py` 다. 여기서 같은
    규칙을 계산하면 진실이 둘이 되고, 어느 쪽이 맞는지 아무도 모르게 된다.

    `스킵사유` 키가 **통째로 없으면 예외**다 — 값이 `None`(스킵 아님)인 것과
    키가 없는 것(산출물 모양이 다르다)은 다른 사실이다.
    """
    if not isinstance(상품, dict):
        raise ValueError(f"상품이 dict 가 아니다: {type(상품).__name__}")
    if "스킵사유" not in 상품:
        raise ValueError("산출물 상품에 '스킵사유' 키가 없다 — 산출물 모양이 다르다. "
                         "없는 것과 못 읽은 것을 같은 값으로 접지 마라")
    사유 = 상품.get("스킵사유")
    if 사유 is None:
        return None
    if not isinstance(사유, str) or not 사유.strip():
        raise ValueError(f"'스킵사유' 의 모양이 다르다: {사유!r}")
    return 사유


def 제품이미지목록(상품: dict, 게이트통과: bool = False, *,
              잔여하한: int | None = None) -> list[str]:
    """Phase 5 가 제품 이미지에 닿는 **유일한 관문** (BANNER-03b / BANNER-04 / T-4-01).

    `게이트통과` 를 명시적으로 `True` 로 넘기지 않으면 예외다. 기본값이 `False` 라
    호출부가 실수로 빼먹으면 못 쓴다 — BANNER-04 의 *"게이트를 통과하기 전에는 상세
    생성 입력으로 쓰이지 않는다"* 를 **구조로** 집행한다. 그 값의 출처는
    `게이트집계(...)["게이트통과"]` 뿐이다. 새 상태를 만들지 않는다 —
    산출물 + 라벨 + 확인에서 매번 계산된다.

    우회로는 전부 `ValueError` 다:
      · 게이트 미통과 · 스킵된 상품 · 미판정 장이 남음 · 제품 이미지 0장 · 하한 미만

    `jobs.py:523-536`·`545-552` 가 세운 "빈 값이 '전량'으로 해석되는 경로는 예외로
    터뜨린다" 규율의 네 번째 적용이다. **메시지에 실측 숫자와 결정 번호를 적는 것**까지
    따라한다 — 그게 다음 사람이 가드를 못 지우게 하는 장치다.

    반환은 URL 리스트다. **원래 순서 유지, 개수 제한 없음**(D-06) — 10장으로 줄이는
    규칙은 Phase 5 몫이고, 여기서 자르면 그게 진짜 누락이다(D-05).
    """
    if not isinstance(상품, dict):
        raise ValueError(f"상품이 dict 가 아니다: {type(상품).__name__}")

    # ① 게이트가 **가장 바깥**이다. 데이터가 아무리 멀쩡해도 사람이 전수를 보기 전에는
    #    Phase 5 입력이 될 수 없다(D-03a / D-12). `게이트통과=1` 같은 참같은 값으로도
    #    열리지 않는다 — 진짜 `True` 여야 한다.
    if 게이트통과 is not True:
        raise ValueError("게이트를 통과하지 않았다 — 제품 이미지 목록은 Phase 5 입력으로 "
                         "쓸 수 없다 (BANNER-04). 값의 출처는 "
                         "게이트집계(...)['게이트통과'] 뿐이다")

    # ② 스킵 — 사유를 그대로 싣는다. 규칙은 재현하지 않고 읽기만 한다(S-1).
    사유 = 스킵사유읽기(상품)
    if 사유:
        raise ValueError(f"스킵된 상품이다: {사유} — Phase 5 입력으로 쓸 수 없다 (D-07/D-08)")

    # ③ 미판정 — "배너 아님"으로 흡수하지 않는다.
    장들 = 상품.get("장")
    if not isinstance(장들, list):
        raise ValueError(f"산출물 상품의 '장' 이 리스트가 아니다: {type(장들).__name__}")
    미판정장 = [c for c in 장들 if isinstance(c, dict) and c.get("판정") == 미판정]
    if 미판정장:
        순번들 = [c.get("순번") for c in 미판정장][:5]
        raise ValueError(f"판정 못 한 장(미판정)이 {len(미판정장)}개 있다{순번들} — "
                         "'배너 아님'으로 흡수하지 마라. 실측 404 2.7% 중 20장이 "
                         "한 상품에 몰렸다")

    # ④ 빈 목록 — '전량'이 아니다.
    제품이미지 = 상품.get("제품이미지")
    if not isinstance(제품이미지, list):
        raise ValueError(f"산출물 상품의 '제품이미지' 가 리스트가 아니다: "
                         f"{type(제품이미지).__name__} — 없는 것을 0장으로 읽지 마라")
    if not 제품이미지:
        raise ValueError("제품 이미지가 0장이다 — 빈 목록은 '전량'이 아니다")

    # ⑤ 하한 — D-07. 임계값 정본은 settings 이고, 여기 상수는 주입이 없을 때의 폴백이다.
    하한 = 기본_잔여하한 if 잔여하한 is None else int(잔여하한)
    if len(제품이미지) < 하한:
        raise ValueError(f"제품 이미지가 {len(제품이미지)}장이다 — D-07 하한({하한}장) 미만")

    urls = []
    for i, 칸 in enumerate(제품이미지):
        if not isinstance(칸, dict) or not isinstance(칸.get("url"), str):
            raise ValueError(f"'제품이미지' {i}번째 칸의 모양이 다르다: {칸!r}")
        urls.append(칸["url"])
    return urls


def _라벨정규화(라벨) -> dict:
    """`{이미지순번: 판정}` 의 순번 키를 정수로 맞춘다.

    라벨은 JSON 을 거쳐 오면 키가 문자열이 된다. 여기서 안 맞추면 `라벨.get(3)` 이
    조용히 빗나가고, **사람이 뒤집은 라벨이 통째로 사라진 채 "동의"로 읽힌다.**
    """
    if 라벨 is None:
        return {}
    if not isinstance(라벨, dict):
        raise ValueError(f"사람라벨 항목이 dict 가 아니다: {type(라벨).__name__}")
    나온것 = {}
    for k, v in 라벨.items():
        try:
            순번 = int(k)
        except (TypeError, ValueError) as e:
            raise ValueError(f"사람라벨의 이미지순번이 정수가 아니다: {k!r}") from e
        if v not in 사람판정허용값:
            raise ValueError(f"사람판정 값이 허용값 {사람판정허용값} 밖이다: {v!r} "
                             "— 사람은 '모르겠다'를 찍지 않는다 (D-09)")
        나온것[순번] = v
    return 나온것


def 게이트집계(산출물: dict, 사람라벨: dict, 검수완료, *,
           누락률상한: float | None = None) -> dict:
    """산출물(기계) + 라벨(사람) + 확인(전수 근거) → 게이트 숫자 (BANNER-04 / D-11 / D-12).

    `사람라벨` 은 `{상품키: {이미지순번: '배너'|'제품'|'무내용'}}` 이고, `검수완료` 는
    "이 줄 확인함"을 누른 상품키 집합이다.

    **분자 규약:**
      · 미탐 = 사람이 `배너` 라 했는데 기계가 `배너` 가 아니라 한 장
      · 오탐 = 사람이 `제품` 이라 했는데 기계가 `배너` 라 한 장
      · `무내용` 뒤집기는 **어느 분자에도 넣지 않는다** — 버려도 내용 누락이 아니고
        남겨도 배너가 게시되지 않는다. 둘 다 사고가 아닌 장을 게이트에 섞으면 숫자가
        흐려진다. 대신 별도 칸으로 보고한다(§1(f) — 숫자 둘을 한 칸에 담지 않는다)

    **분모 둘을 모두 낸다** (D-11):
      · `오탐율_정밀도` = 오탐 / 기계가 배너라 한 장   (실측 15.6% — **기각한 대안**)
      · `오탐율_누락률` = 오탐 / 사람이 제품이라 한 장 (실측 1.8% — **채택**)

    누락률을 고른 근거는 D-05 다: *"내용 누락이 크레딧 절약보다 나쁘다."* 그 문장이 묻는
    숫자가 정확히 "전체 제품 이미지 중 몇 %를 잃었나"다. 정밀도는 같은 오류를 더 엄격하게
    읽는 값이고, 판정 폭주 방지는 **D-08 이 상품 단위로 이미 잡는다.**
    두 숫자를 모두 화면에 띄우되 **게이트 판정만** 누락률로 한다.

    **라벨이 없는 장은 "기계 판정에 동의"로 읽는다** — 단, 그 상품을 실제로 봤을 때만
    그렇다(D-03a). 확인 표시가 없는 상품은 분모에서 빼고 `미검수상품` 으로 따로 보고한다.
    안 본 것을 동의로 세면 미탐 0% 가 거짓말이 된다(Pitfall 8).

    `게이트통과` = `미검수상품 == 0` **그리고** `미탐 == 0` **그리고**
    `오탐율_누락률 <= 상한`. 미검수가 하나라도 있으면 통과할 수 없다 — **전수가 전제다**(D-12).
    """
    if not isinstance(산출물, dict) or not isinstance(산출물.get("상품"), list):
        raise ValueError("산출물에 '상품' 리스트가 없다 — 못 읽은 것을 0건으로 읽지 마라")
    if 사람라벨 is None or not isinstance(사람라벨, dict):
        raise ValueError(f"사람라벨이 dict 가 아니다: {type(사람라벨).__name__}")
    if isinstance(검수완료, str) or 검수완료 is None:
        # 문자열을 그대로 받으면 글자 단위로 순회해 "전부 검수됨"처럼 보인다.
        raise ValueError("검수완료는 상품키 집합이어야 한다 (문자열·None 불가)")
    확인됨 = {str(k) for k in 검수완료}

    # 물갈이 사본을 **한 번만** 센다 (성공기준 4). 첫 사본을 대표로 삼는다.
    대표: dict[str, dict] = {}
    순서: list[str] = []
    for 상품 in 산출물["상품"]:
        키 = 상품키(상품)
        if 키 in 대표:
            continue
        대표[키] = 상품
        순서.append(키)

    검수된키 = [k for k in 순서 if k in 확인됨]
    r = {"검수상품": len(검수된키), "미검수상품": len(순서) - len(검수된키),
         "사람배너": 0, "사람제품": 0, "기계배너": 0,
         "미탐": 0, "오탐": 0, "무내용뒤집기": 0}

    for 키 in 검수된키:
        장들 = 대표[키].get("장")
        if not isinstance(장들, list):
            raise ValueError(f"상품 {키} 의 '장' 이 리스트가 아니다 — 검수 화면은 "
                             "전장을 깐다(D-03a). 장 목록이 없으면 집계가 성립하지 않는다")
        라벨 = _라벨정규화(사람라벨.get(키))
        for 장 in 장들:
            if not isinstance(장, dict):
                raise ValueError(f"상품 {키} 의 장이 dict 가 아니다: {type(장).__name__}")
            기계 = 장.get("판정")
            if 기계 not in _장판정허용값:
                raise ValueError(f"상품 {키} 의 장 판정이 허용값 밖이다: {기계!r}")
            try:
                순번 = int(장.get("순번"))
            except (TypeError, ValueError) as e:
                raise ValueError(f"상품 {키} 의 장 순번이 정수가 아니다: "
                                 f"{장.get('순번')!r}") from e

            # 클릭 안 함 = 기계 판정에 동의 (그 줄을 실제로 봤다는 근거가 위에서 확보됐다).
            사람 = 라벨.get(순번, 기계)
            if 사람 == 미판정:
                # 기계도 못 봤고 사람도 안 뒤집었다. **분모에 넣지 않는다** —
                # 판정이 없는 장을 동의로 세면 그것도 자기기만이다.
                continue

            r["사람배너"] += 사람 == 배너
            r["사람제품"] += 사람 == 제품
            r["기계배너"] += 기계 == 배너
            if 사람 == 배너 and 기계 != 배너:
                r["미탐"] += 1
            if 사람 == 제품 and 기계 == 배너:
                r["오탐"] += 1
            if 사람 != 기계 and 무내용 in (사람, 기계):
                r["무내용뒤집기"] += 1

    # 분모가 0 이면 `None` 이다. 0 으로 나누지도, 0.0 으로 접지도 않는다 —
    # **0건은 관측이 아니다.** 그리고 관측이 없으면 게이트는 닫혀 있어야 한다.
    r["오탐율_정밀도"] = (r["오탐"] / r["기계배너"]) if r["기계배너"] else None
    r["오탐율_누락률"] = (r["오탐"] / r["사람제품"]) if r["사람제품"] else None

    상한 = 기본_누락률상한 if 누락률상한 is None else float(누락률상한)
    r["게이트통과"] = bool(
        r["미검수상품"] == 0
        and r["미탐"] == 0
        and r["오탐율_누락률"] is not None
        and r["오탐율_누락률"] <= 상한
    )
    return r
