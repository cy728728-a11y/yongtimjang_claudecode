#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""상세 상태 3단계 판정 — 불사자가 써 둔 플래그를 **읽기만** 한다 (STATE-02/03/04/05).

**순수 함수뿐이다. 네트워크도 크레딧도 파일도 0 이다.** dict 하나를 받아 문자열 하나를 낸다.
`board.py` 와 같은 성질이다 — CLI 가 이미 써 둔 산출물을 투영할 뿐, 판정 대상을 직접
조회하지 않는다. 그래서 회차 파일이 없어도, 불사자가 죽어 있어도 이 모듈은 안 깨진다.

근거 필드는 두 개다. 하나로는 안 갈린다 (2026-09-21 실측 34건):
  · aiImageGenerated — 불사자 AI 상세 생성 흔적. **키 자체가 없을 수 있다**
  · imageTranslated  — 원본 상세 이미지 번역 흔적. 타입이 제각각이다
AI 생성분 8건의 `imageTranslated` 실측이 '0' 3건 / '1' 5건으로 섞여 있다 —
**번역 플래그 단독으로는 3단계가 안 갈린다.**

이 모듈이 절대 하지 않는 것:
  - 불사자 MCP 호출 (D-19). 불사자 클라이언트 라이브러리를 import 하지 않는다 —
    웹앱 전용 venv 에는 그 라이브러리가 쓰는 HTTP 패키지가 없어서 import 하는 순간
    ImportError 다. MCP 접촉은 전부 CLI 자식 프로세스 몫이다
  - 내장 캐스팅으로 플래그 읽기. 비어 있지 않은 문자열은 전부 참이라 `'0'` 이
    True 가 되고, 🔴 상품이 통째로 🟡 로 뒤집힌다. 반드시 `불리언정규화` 를 거친다
  - `dc["aiImageGenerated"]` 로 꺼내기. 키가 **통째로 없다** (실측 34건 중 26건).
    `.get()` 만 쓴다 — `board.py:36-40` 의 ①·⑥ 행 규율과 같은 부류다
  - `상세페이지있음`(summary 응답 최상위)으로 판정. 34건 **전부 True** 라 기준이 못 된다.
    `detail_batch.py:140` 의 주석이 이미 경고한다: "원본 번역 이미지만 있어도 true"
  - 태그(`구매_가공완료`)와 기계기록(`aiImageGenerated`)을 **한 값으로 합치기** (Pitfall 8).
    태그는 용팀장의 손자국이고 기계기록은 불사자가 찍은 것이다. 같은 걸 뜻하지 않는다.
    합치면 D-08 이 요구하는 "회색으로 보이되 직접 선택 가능" 이 불가능해진다
  - 판정값을 캐시하기. 불사자 서버 플래그가 정본이고(PROJECT.md), 캐시하는 순간
    Phase 5 가 낡은 상태로 크레딧을 태운다

## STATE-04 확정 — 외부 반영 경로는 `aiImageGenerated` 를 찍지 않는다

불사자 외부 반영 도구(GPTs 로 가공한 이미지를 올려 HTML 을 교체하는 경로)는 AI 생성
카운터를 건드리지 않는다. **양성대조 8건 전부 `aiImageGenerated=True`(생성일·장수 정상),
음성대조 26건 전부 키 부재** (2026-09-21 실측 34건). 양성대조가 지금도 살아 있으므로
"API 에서 필드가 사라졌다" 는 대안 가설은 배제된다.

그래서 **외부 경로 기작업의 유일한 신호는 `그룹` 태그**이고, 그 태그는 불사자 목록 조회
응답에 이미 들어 있다 — 추가 API 호출 0. 보완 인덱스를 신설하지 않는다(D-09).
이 결론의 검증 수단은 이 문서 자체다(`03-VALIDATION.md` STATE-04 행).

## 한글 함수명에 대해

저장소 관례는 "공개 API 는 영문, 내부 이름은 한글"이다(`board.py` 의 `fold_products`).
여기서만 공개 함수도 한글인 이유: 판정 규약의 정본이 `03-RESEARCH.md:338-380` 의 코드이고,
`03-VALIDATION.md` 의 테스트 이름이 그 이름을 그대로 지목한다. 정본을 따른다.
"""

# 판정값. **이모지는 화면에서 붙인다** — 여기서는 문자열이다.
# 화면 표시는 ⚪ AI가공완료 / 🟡 단순번역만 / 🔴 중국어원본.
AI가공완료 = "AI가공완료"
단순번역만 = "단순번역만"
중국어원본 = "중국어원본"

# 실측 타입: 문자열 '1' / 문자열 '0' / 불리언 False / 키 부재(None).
# 요구사항(STATE-02)이 예고한 int 1 은 이번 34건에서는 못 봤다 — 그래도 같이 받는다.
_FALSY = {"0", "false", "no", "n", "", "none", "null"}


def 불리언정규화(v) -> bool:
    """'0' '1' False 1 None 을 전부 같은 규약으로 읽는다.

    파이썬 내장 캐스팅을 그대로 쓰지 마라 — 문자열 '0' 은 파이썬에서 **참**이다.
    실측에서 `imageTranslated` 가 문자열 '0' 으로 오는 상품이 있었다.
    그대로 태우면 🔴 상품이 전부 🟡 로 뒤집힌다.

    분기 순서에도 의미가 있다. `bool` 은 `int` 의 하위타입이라 숫자 분기를 앞에 두면
    `True`/`False` 가 숫자 경로로 새고, 그 값이 화면까지 가면 `예/아니오` 대신 `1/0` 이
    찍힌다 (`board.js:68-72` 가 같은 함정을 JS 쪽에 적어 뒀다).
    반환은 항상 진짜 `bool` 객체다 — 입력을 그대로 돌려주지 않는다.
    """
    if v is None:
        return False
    if isinstance(v, bool):
        return v
    if isinstance(v, (int, float)):
        return v != 0
    return str(v).strip().lower() not in _FALSY


def 상세상태(uploadDetailContents) -> str:
    """🔴 중국어원본 / 🟡 단순번역만 / ⚪ AI가공완료 중 하나 (STATE-03).

    **판정 순서에 의미가 있다** — AI 생성분에도 `imageTranslated` 가 '1' 로 남아 있어서
    (실측 8건 중 5건) 번역 여부를 먼저 보면 ⚪가 🟡로 내려앉는다. 그러면 Phase 5 가
    **이미 가공된 상품에 크레딧을 다시 태운다.** 이 페이즈에서 가장 조용한 버그다.

    dict 가 아닌 것(None·리스트·문자열)이 와도 예외를 내지 않는다 — 조인이 안 풀린 행이
    이 함수까지 올 수 있고, 거기서 터지면 회차 하나가 통째로 안 뜬다.
    """
    dc = uploadDetailContents if isinstance(uploadDetailContents, dict) else {}
    if 불리언정규화(dc.get("aiImageGenerated")):
        return AI가공완료          # ⚪
    if 불리언정규화(dc.get("imageTranslated")):
        return 단순번역만          # 🟡
    return 중국어원본              # 🔴


def 기작업여부(그룹태그, dc, done_tags) -> bool:
    """이미 상세가 가공된 상품인가 — **두 신호의 OR** 다 (STATE-04/05 / D-08 / D-10).

      ① `그룹태그` 가 `done_tags` 안에 있다      — 사람 손자국(외부 반영 경로)
      ② `상세상태(dc) == AI가공완료`             — 기계 기록(불사자 AI 생성 경로)

    하나만 보면 반드시 샌다. 태그만 보면 불사자 AI 생성분을 놓치고, 기계기록만 보면
    외부 경로 기작업분을 놓쳐 **크레딧을 다시 태운다** (실측 그룹 하나에만 18건).

    `done_tags` 를 인자로 받는 이유: 이 모듈이 설정을 직접 읽으면 테스트가 값을
    갈아끼울 자리가 애매해지고, 호출부(`join.attach`)가 어차피 설정을 읽는다.
    빈 목록이면 기계기록만 본다 — **설정이 비었다고 전량 기작업이 되면 안 된다.**

    ⚠️ 목표 장수(`pages`)를 **인자로 받지 않는다.** 현행 CLI 는
    `prev["pages"] >= min(목표장수, 수집이미지수)` 로 스킵을 판정하는데, 그러면 8장짜리
    기작업 상품이 이번에 이미지 10장을 모았을 때 재접수돼 크레딧을 다시 낸다.
    **기작업 스킵은 목표 장수와 무관한 절대 조건이다** (STATE-05 / D-10).

    ⚠️ 이 값은 `상세상태` 와 **별개의 반환값**이다. 한 값으로 합치지 마라 (Pitfall 8).
    """
    태그 = (그룹태그 or "").strip()
    if 태그 and 태그 in {str(t).strip() for t in (done_tags or ())}:
        return True
    return 상세상태(dc) == AI가공완료
